// Builds the in-chat results widget into ../widget_html.mjs (owner, 2026-11-27).
// The chat host shows the widget in a sandboxed iframe that blocks scripts from other sites, so the ext-apps
// bridge and Leaflet are inlined. Run from this folder: npm install && node build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const read = p => readFileSync(require.resolve(p), 'utf8');

// The bridge ships as ESM ending in export{...}; turn that into a global the page script can read
const bundle = read('@modelcontextprotocol/ext-apps/app-with-deps').replace(/export\{([^}]+)\};?\s*$/, (_, body) =>
  'globalThis.ExtApps={' + body.split(',').map(pair => {
    const [local, exported] = pair.split(' as ').map(s => s.trim());
    return `${exported ?? local}:${local}`;
  }).join(',') + '};');
if (!bundle.includes('globalThis.ExtApps=')) throw new Error('ext-apps bundle export not found; check the package version');

// Every replacement uses a function so "$" sequences in minified code are kept as they are
const html = readFileSync(new URL('./results.html', import.meta.url), 'utf8')
  .replace('/*__LEAFLET_CSS__*/', () => read('leaflet/dist/leaflet.css'))
  .replace('/*__LEAFLET_JS__*/', () => read('leaflet/dist/leaflet.js').replace(/<\/script/gi, '<\\/script'))
  .replace('/*__EXT_APPS_BUNDLE__*/', () => bundle.replace(/<\/script/gi, '<\\/script'));
if (/\/\*__[A-Z_]+__\*\//.test(html)) throw new Error('a placeholder was not replaced');

const out = '// GENERATED by automation/widget/build.mjs from results.html. Do not edit by hand.\n'
  + `export const WIDGET_HTML = ${JSON.stringify(html)};\n`;
writeFileSync(new URL('../widget_html.mjs', import.meta.url), out);
console.log(`widget_html.mjs: ${(out.length / 1024).toFixed(0)} KB`);
